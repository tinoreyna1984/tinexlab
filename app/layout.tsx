import type { Metadata } from "next";
import { Geist, Geist_Mono, Quicksand } from "next/font/google";

import { SplashScreen } from "@/components/splash-screen";
import { splashStorageKey } from "@/lib/splash";

import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const quicksand = Quicksand({
  variable: "--font-quicksand",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
  icons: { icon: "/tinexlab-logo.png" },
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    // suppressHydrationWarning: el script inline cambia data-splash en <html>
    // antes de hidratar; sin él, React descartaría el DOM corregido y el
    // splash parpadearía en visitas repetidas (guía "Preventing Flash" de
    // Next 16, ver design.md D2).
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} ${quicksand.variable} h-full antialiased`}
      suppressHydrationWarning
    >
      <head>
        {/* Pre-paint: si la sesión ya vio el splash, se marca <html> antes
            del primer pintado para que CSS lo oculte sin parpadeo. */}
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){try{if(sessionStorage.getItem(${JSON.stringify(
              splashStorageKey,
            )}))document.documentElement.setAttribute("data-splash","seen")}catch(e){}})()`,
          }}
        />
      </head>
      <body className="min-h-full flex flex-col">
        <SplashScreen />
        {children}
      </body>
    </html>
  );
}
